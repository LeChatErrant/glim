// Golden dust on a warm clear day: glowing motes rising slowly (tinted to the hour's light).
{
  const r = rng(29);
  let glow = '';
  let core = '';
  for (let i = 0; i < 22; i++) {
    const x = 8 + r() * (F - 16);
    const y = r() * F;
    glow += `<group android:translateX="${f(x)}" android:translateY="${f(y)}"><path android:pathData="${circle(0, 0, 5)}">${radialFill(5, [[0, '#40FFFFFF'], [1, '#00FFFFFF']])}</path></group>`;
    core += circle(x, y, 0.9);
  }
  const one = `${glow}<path android:fillColor="#E6FFFFFF" android:pathData="${core}"/>`;
  const body = `<group android:name="sway"><group android:name="fall"><group>${one}</group><group android:translateY="${F}">${one}</group></group></group>`;
  write('dust', true, F, F, body, { fall: [anim('translateY', 0, -F, 140000)], sway: [anim('translateX', -4, 4, 9700, true)] });
}

/** Soft blobs drifting side to side (fog banks, cloud shadows), white: tinted from JS. */
function blobs(name, banks) {
  let body = '';
  const targets = {};
  banks.forEach(({ seed, n, rx, ry, a, drift, ms }, k) => {
    const r = rng(seed);
    let g = '';
    for (let i = 0; i < n; i++) {
      const x = -60 + r() * (F + 120);
      const y = r() * F;
      const sx = (rx[0] + r() * (rx[1] - rx[0])) / 100;
      const sy = (ry[0] + r() * (ry[1] - ry[0])) / 100;
      g += `<group android:translateX="${f(x)}" android:translateY="${f(y)}" android:scaleX="${f(sx)}" android:scaleY="${f(sy)}"><path android:pathData="${circle(0, 0, 100)}">${radialFill(100, [
        [0, hex(a, 'FFFFFF')],
        [0.5, hex(a * 0.5, 'FFFFFF')],
        [1, '#00FFFFFF'],
      ])}</path></group>`;
    }
    body += `<group android:name="drift${k}">${g}</group>`;
    targets[`drift${k}`] = [anim('translateX', -drift, drift, ms, true)];
  });
  write(name, true, F, F, body, targets);
}
// Long wisps drifting both ways (fog banks; a pearl sky's thin clouds), breathing. Full white:
// JS tints them with the alpha (thick fog, thin wisps).
{
  const r = rng(13);
  let body = '';
  const targets = {};
  const count = 8;
  for (let i = 0; i < count; i++) {
    const x = r() * F;
    const y = ((i + 0.3 * r()) / count) * F + 8;
    const sx = (90 + 55 * r()) / 100;
    const sy = (15 + 13 * r()) / 100;
    const dir = i % 2 ? -1 : 1;
    body += `<group android:name="w${i}"><group android:translateX="${f(x)}" android:translateY="${f(y)}" android:scaleX="${f(sx)}" android:scaleY="${f(sy)}"><path android:name="p${i}" android:pathData="${circle(0, 0, 100)}">${radialFill(100, [
      [0, '#FFFFFFFF'],
      [0.45, hex(0.62, 'FFFFFF')],
      [1, '#00FFFFFF'],
    ])}</path></group></group>`;
    targets[`w${i}`] = [anim('translateX', -dir * (30 + 20 * r()), dir * (30 + 20 * r()), 50000 + 30000 * r(), true)];
    targets[`p${i}`] = [anim('fillAlpha', 0.55, 1, 17000 + 12000 * r(), true)];
  }
  write('fog', true, F, F, body, targets);
}
