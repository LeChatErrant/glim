// Writes the Map widget's weather animations as Android resources (modules/hue-http): each kind
// is an animated vector played by an indeterminate ProgressBar, which the launcher animates on
// its own at the screen's frame rate. Run `node scripts/widget-fx.mjs` after changing it, then
// rebuild. JS (src/lib/weather/scene.ts, widgetOutside) picks kinds and places them; Kotlin
// (WidgetOutside.kt) adds them to the widget.
//
// Two shapes of kinds:
// - full: a 300×300 field shown in a square as big as the widget's longer side, centered;
// - placed: a small view at a point (fireflies, moths, ripples...), several variants per kind,
//   each with its own period and phase so they never move in step.
// Periods differ between layers, so the whole picture never visibly loops.
import fs from 'node:fs';
import path from 'node:path';

const RES = 'modules/hue-http/android/src/main/res';
const KT = 'modules/hue-http/android/src/main/java/io/lechaterrant/huehttp/FxKinds.kt';

const f = (v) => String(Number(v.toFixed(2)));
const fr = (v) => v.toFixed(4);
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const hex = (a, rgb) => `#${Math.round(a * 255).toString(16).padStart(2, '0').toUpperCase()}${rgb}`;
const circle = (x, y, r) => `M${f(x - r)},${f(y)}a${f(r)},${f(r)} 0 1,0 ${f(2 * r)},0a${f(r)},${f(r)} 0 1,0 ${f(-2 * r)},0z`;
const ellipse = (x, y, rx, ry) => `M${f(x - rx)},${f(y)}a${f(rx)},${f(ry)} 0 1,0 ${f(2 * rx)},0a${f(rx)},${f(ry)} 0 1,0 ${f(-2 * rx)},0z`;
const streak = (x, y, w, h) => `M${f(x)},${f(y)}h${f(w)}v${f(h)}h${f(-w)}z`;
const radialFill = (r, stops) =>
  `<aapt:attr name="android:fillColor"><gradient android:type="radial" android:centerX="0" android:centerY="0" android:gradientRadius="${f(r)}">${stops
    .map(([o, c]) => `<item android:offset="${o}" android:color="${c}"/>`)
    .join('')}</gradient></aapt:attr>`;

const INTERP = { linear: '@android:anim/linear_interpolator', ease: '@android:anim/accelerate_decelerate_interpolator' };
/** A property going from → to forever: restarting, or back and forth (`reverse`, eased). */
const anim = (prop, from, to, ms, reverse = false) =>
  `<objectAnimator android:propertyName="${prop}" android:valueFrom="${f(from)}" android:valueTo="${f(to)}" android:valueType="floatType" android:duration="${Math.round(ms)}" android:repeatCount="infinite"${
    reverse ? ' android:repeatMode="reverse"' : ''
  } android:interpolator="${reverse ? INTERP.ease : INTERP.linear}"/>`;

/**
 * Keyframes for `fn` over one period, started at `phase`: t = (u + phase) mod 1. The jump where
 * the period starts again stays a jump (two keyframes a hair apart), so rings don't shrink back.
 */
function cycle(fn, phase, n = 32) {
  const cut = (1 - phase) % 1;
  const us = [];
  for (let i = 0; i <= n; i++) {
    const u = i / n;
    if (cut > 0 && Math.abs(u - cut) < 0.002) continue;
    us.push(u);
  }
  const out = [];
  for (const u of us) {
    if (cut > 0 && out.length && out[out.length - 1][0] < cut && u > cut) {
      out.push([cut - 0.0005, fn(1)], [cut, fn(0)]);
    }
    // The period's end: approached from below (fn(1) when it starts at 0).
    out.push([u, u === 1 && phase === 0 ? fn(1) : fn((u + phase) % 1)]);
  }
  return out;
}
const keys = (ms, holders) =>
  `<objectAnimator android:duration="${Math.round(ms)}" android:repeatCount="infinite" android:interpolator="${INTERP.linear}">${holders
    .map(
      ([prop, kfs]) =>
        `<propertyValuesHolder android:propertyName="${prop}" android:valueType="floatType">${kfs.map(([u, v]) => `<keyframe android:fraction="${fr(u)}" android:value="${f(v)}"/>`).join('')}</propertyValuesHolder>`,
    )
    .join('')}</objectAnimator>`;

const kinds = []; // [name, full]

function write(name, full, w, h, body, targets) {
  const t = Object.entries(targets)
    .map(([target, anims]) => `  <target android:name="${target}"><aapt:attr name="android:animation">${anims.length > 1 ? `<set>${anims.join('')}</set>` : anims[0]}</aapt:attr></target>`)
    .join('\n');
  fs.writeFileSync(
    path.join(RES, 'drawable', `glim_fx_${name}.xml`),
    `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/widget-fx.mjs: don't edit. -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt">
  <aapt:attr name="android:drawable">
    <vector android:width="${w}dp" android:height="${h}dp" android:viewportWidth="${w}" android:viewportHeight="${h}">${body}</vector>
  </aapt:attr>
${t}
</animated-vector>
`,
  );
  fs.writeFileSync(
    path.join(RES, 'layout', `glim_fx_${name}.xml`),
    `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/widget-fx.mjs: don't edit. -->
<ProgressBar xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@id/glim_fx_view"
    android:layout_width="${full ? 'match_parent' : '1dp'}"
    android:layout_height="${full ? 'match_parent' : '1dp'}"
    android:layout_gravity="${full ? 'center' : 'top|start'}"
    android:importantForAccessibility="no"
    android:indeterminate="true"
    android:indeterminateOnly="false"
    android:indeterminateDrawable="@drawable/glim_fx_${name}"
    android:minWidth="0dp"
    android:minHeight="0dp"
    android:maxWidth="4000dp"
    android:maxHeight="4000dp" />
`,
  );
  kinds.push([name, full]);
}

// ---- Full fields (300×300) ----

const F = 300;

/**
 * Falling (or rising, `dir` -1) particle layers, all in one vector (the launcher redraws a whole
 * vector each frame: one big one is much cheaper than three). Copies above and below make each
 * slide seamless; each layer has its own speed, so the field never visibly loops.
 */
function layered(layers) {
  let body = '';
  const targets = {};
  layers.forEach(({ seed, n, draw, color, ms, dir = 1, angle = 0, sway = 0, swayMs = 1, xs = [2, F - 2] }, i) => {
    const r = rng(seed);
    let d = '';
    for (let k = 0; k < n; k++) d += draw(xs[0] + r() * (xs[1] - xs[0]), r() * F, r);
    const copies = (angle ? [-F, 0, F] : [0, -dir * F]).map((y) => `<group android:translateY="${y}"><path android:fillColor="${color}" android:pathData="${d}"/></group>`).join('');
    const inner = `<group android:name="fall${i}">${copies}</group>`;
    const swayed = sway ? `<group android:name="sway${i}">${inner}</group>` : inner;
    body += angle ? `<group android:rotation="${angle}" android:pivotX="${F / 2}" android:pivotY="${F / 2}">${swayed}</group>` : swayed;
    targets[`fall${i}`] = [anim('translateY', 0, dir * F, ms)];
    if (sway) targets[`sway${i}`] = [anim('translateX', -sway, sway, swayMs, true)];
  });
  return { body, targets };
}

